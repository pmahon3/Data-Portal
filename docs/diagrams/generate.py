"""
Generate the diagrams in docs/diagrams/generated/ from the code, so they can't drift from it.

    python3 docs/diagrams/generate.py           write them
    python3 docs/diagrams/generate.py --check   fail if any differs from what the code gives

What each diagram is read from:
- Packages and modules: the import statements of the backend and the file service (Python's own
  parser; tests excluded). An arrow A --> B means code in A imports from B.
- Neighbourhoods (data standards, notifications): one package's modules, what imports them and
  what they import.
- Deployment: the Docker Compose files (following `include`), giving services, their images or
  builds, published ports, and `depends_on`.

Needs PyYAML for the Compose files (`uv run --no-project --with pyyaml python docs/diagrams/generate.py`).
"""
from __future__ import annotations

import ast
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "diagrams" / "generated"
HEADER = ("<!-- Generated by docs/diagrams/generate.py from the code. Don't edit: change the code, then "
          "run the generator. -->\n")
SKIP = {"tests", "e2e", "tests_os", "contract", "scripts", "__pycache__"}


def modules(root: Path) -> dict[str, Path]:
    """Dotted module name -> file, for every Python file under ``root`` outside tests and scripts."""
    found = {}
    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root)
        if SKIP & set(rel.parts[:-1]) or rel.name.startswith("test_") or rel.name == "conftest.py":
            continue
        parts = list(rel.with_suffix("").parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        if parts and (path.name != "__init__.py" or path.read_text().strip()):  # an empty __init__ draws nothing
            found[".".join(parts)] = path
    return found


def imports(root: Path) -> dict[str, set[str]]:
    """Module -> the modules of the same component it imports (absolute or relative)."""
    mods = modules(root)
    PACKAGES.update({name: path.name == "__init__.py" for name, path in mods.items()})
    for name in mods:  # folders without an __init__ are packages too
        for i in range(1, name.count(".") + 1):
            PACKAGES.setdefault(".".join(name.split(".")[:i]), True)
    edges = defaultdict(set)
    for name, path in mods.items():
        package = name if path.name == "__init__.py" else name.rpartition(".")[0]
        for node in ast.walk(ast.parse(path.read_text(), str(path))):
            targets = []
            if isinstance(node, ast.Import):
                targets = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom):
                base = node.module or ""
                if node.level:
                    up = package.split(".")[: len(package.split(".")) - node.level + 1] if package else []
                    base = ".".join([*up, base] if base else up)
                targets = [f"{base}.{a.name}" if base else a.name for a in node.names] + [base]
            for target in targets:
                while target and target not in mods:  # `from a.b import c`: c may be a name in a.b
                    target = target.rpartition(".")[0]
                if target and target != name:
                    edges[name].add(target)
        edges.setdefault(name, set())
    return dict(edges)


PACKAGES: dict[str, bool] = {}  # dotted name -> is a package (a folder), filled by imports()


def package_of(module: str, depth: int) -> str:
    """The folder a module is in (a package is its own folder), at most ``depth`` levels down."""
    parts = module.split(".")
    folder = parts if PACKAGES.get(module) else parts[:-1]
    return ".".join(folder[:depth]) or module


def collapse(edges: dict[str, set[str]], depth: int) -> dict[str, set[str]]:
    """The same graph with modules grouped into their folders, at most ``depth`` levels down."""
    out = defaultdict(set)
    for a, targets in edges.items():
        pa = package_of(a, depth)
        out.setdefault(pa, set())
        for b in targets:
            if package_of(b, depth) != pa:
                out[pa].add(package_of(b, depth))
    return dict(out)


def node_id(name: str) -> str:
    return re.sub(r"\W", "_", name) or "root"


def flowchart(edges: dict[str, set[str]], label=lambda n: n.replace(".", "/"), direction="LR",
              layer=lambda n: None) -> str:
    """A Mermaid flowchart of ``edges``; ``layer`` names the box a node is drawn in (None: no box)."""
    lines = [f"flowchart {direction}"]
    layers = defaultdict(list)
    for n in sorted(edges):
        layers[layer(n)].append(n)
    for name in sorted(layers, key=lambda x: (x is not None, x or "")):
        indent = "  "
        if name is not None:
            lines.append(f'  subgraph {node_id("layer." + name)}["{name}"]')
            indent = "    "
        for n in layers[name]:
            lines.append(f'{indent}{node_id(n)}["{label(n)}"]')
        if name is not None:
            lines.append("  end")
    for a in sorted(edges):
        for b in sorted(edges[a]):
            lines.append(f"  {node_id(a)} --> {node_id(b)}")
    return "\n".join(lines)


def neighbourhood(edges: dict[str, set[str]], package: str, depth: int) -> dict[str, set[str]]:
    """A package's modules, with the packages that import them and the packages they import."""
    inside = {m for m in edges if m == package or m.startswith(package + ".")}
    def outer(m):
        return m if m in inside else package_of(m, depth)
    out = defaultdict(set)
    for a, targets in edges.items():
        for b in targets:
            if a in inside or b in inside:
                if outer(a) != outer(b):
                    out[outer(a)].add(outer(b))
                    out.setdefault(outer(b), set())
    for m in inside:
        out.setdefault(m, set())
    return dict(out)


def compose_services(path: Path, yaml) -> dict[str, dict]:
    """Services of a Compose file, with those of the files it includes; a build context is given
    relative to the repository."""
    data = yaml.safe_load(path.read_text()) or {}
    services = {}
    for inc in data.get("include", []) or []:
        inc_path = inc if isinstance(inc, str) else (inc.get("path") if isinstance(inc.get("path"), str) else inc["path"][0])
        services.update(compose_services((path.parent / inc_path).resolve(), yaml))
    for name, spec in (data.get("services") or {}).items():
        spec = dict(spec or {})
        if spec.get("build") is not None:
            context = spec["build"] if isinstance(spec["build"], str) else spec["build"].get("context", ".")
            spec["build"] = str((path.parent / context).resolve().relative_to(ROOT))
        services[name] = spec
    return services


def merged(paths: list[Path], yaml) -> dict[str, dict]:
    """Services of Compose files applied in order, as `docker compose -f a -f b` does (later keys win)."""
    services = {}
    for path in paths:
        for name, spec in compose_services(path, yaml).items():
            services[name] = {**services.get(name, {}), **spec}
    return services


def deployment(services: dict[str, dict]) -> str:
    lines = ["flowchart LR"]
    for name in sorted(services):
        spec = services[name]
        source = f"build {spec['build']}" if spec.get("build") else f"image {spec.get('image', '?')}"
        ports = ", ".join(str(p).replace('"', "") for p in spec.get("ports", []) or [])
        replicas = (spec.get("deploy") or {}).get("replicas")
        text = (f"{name}<br/>{source}" + (f"<br/>ports {ports}" if ports else "")
                + (f"<br/>replicas {replicas}" if replicas else ""))
        lines.append(f'  {node_id(name)}["{text}"]')
    for name in sorted(services):
        deps = services[name].get("depends_on") or []
        for dep in sorted(deps if isinstance(deps, list) else deps.keys()):
            if dep in services:
                lines.append(f"  {node_id(name)} --> {node_id(dep)}")
    return "\n".join(lines)


def nomad_jobs(path: Path) -> list[tuple[str, str, int, list[tuple[str, str]], list[str]]]:
    """(job, group, count, [(task, image)], [service names]) for each group of a Nomad job file,
    read from its block structure (job, group, task, service) and their count, image and name."""
    groups, stack, current, heredoc = [], [], None, None
    for raw in path.read_text().splitlines():
        if heredoc:  # a template's text, up to its closing marker
            heredoc = None if raw.strip() == heredoc else heredoc
            continue
        line = raw.split("#", 1)[0].strip()
        if m := re.search(r"<<-?(\w+)$", line):
            heredoc = m.group(1)
            continue
        m = re.match(r'(\w+)\s*(?:"([^"]*)"|=)?\s*\{$', line)
        if m:
            kind, label = m.group(1), m.group(2) or ""
            stack.append((kind, label))
            if kind == "group":
                current = [next(l for k, l in stack if k == "job"), label, 1, [], []]
                groups.append(current)
            elif kind == "task" and current:
                current[3].append([label, ""])
            continue
        if (m := re.match(r'\w+\s*\{(.*)\}$', line)):  # a block on one line: `config { image = "x" }`
            line = m.group(1).strip()
            if current and current[3] and (m := re.match(r"image\s*=\s*(.+)", line)):
                current[3][-1][1] = m.group(1).strip().strip('"')
            continue
        if line.startswith("}"):
            if stack and stack.pop()[0] == "group":
                current = None
            continue
        kinds = [k for k, _ in stack]
        if current and (m := re.match(r"count\s*=\s*(\d+)", line)) and kinds[-1] == "group":
            current[2] = int(m.group(1))
        elif current and (m := re.match(r"image\s*=\s*(.+)", line)) and "task" in kinds and current[3]:
            current[3][-1][1] = m.group(1).strip().strip('"')
        elif current and (m := re.match(r'name\s*=\s*"([^"]+)"', line)) and kinds[-1] == "service":
            current[4].append(m.group(1))
    return [(j, g, c, [tuple(t) for t in ts], s) for j, g, c, ts, s in groups]


def nomad(paths: list[Path]) -> str:
    lines = ["flowchart LR"]
    for path in paths:
        for job, group, count, tasks, services in nomad_jobs(path):
            gid = node_id(f"{job}.{group}")
            lines.append(f'  subgraph {gid}["{job} / {group} · count {count}"]')
            for task, image in tasks:
                lines.append(f'    {node_id(f"{job}.{task}")}["{task}<br/>image {image or "?"}"]')
            lines.append("  end")
            for service in sorted(services):
                lines.append(f'  {node_id("svc." + service)}(["service {service}"]) --- {gid}')
    return "\n".join(lines)


def page(title: str, intro: str, diagrams: list[tuple[str, str]]) -> str:
    body = [HEADER, f"# {title}\n", intro + "\n"]
    for heading, chart in diagrams:
        body.append(f"## {heading}\n\n```mermaid\n{chart}\n```\n")
    return "\n".join(body)


def backend_layer(package: str) -> str:
    """The backend layer a package belongs to: api, core/services, core/db, core/storage_agents, ..."""
    parts = package.split(".")
    return "/".join(parts[:2]) if parts[0] == "core" and len(parts) > 1 else parts[0]


def pages() -> dict[str, str]:
    import yaml

    backend = imports(ROOT / "backend")
    gateway = imports(ROOT / "storage-gateway")
    out = {
        "backend.md": page(
            "Backend packages",
            "The backend's folders (at most three levels down, for example `core/services/policies`), boxed by layer. "
            "An arrow means code in one imports from the other.",
            [("Packages", flowchart(collapse(backend, 3), layer=backend_layer))]),
        "file-service.md": page(
            "File service modules",
            "The POSIX file service (`storage-gateway/`), module by module. An arrow means one imports the other.",
            [("Modules", flowchart(gateway))]),
        "data-standards.md": page(
            "Data standards",
            "The standards package (`core/services/standards`), what uses it and what it uses.",
            [("Neighbourhood", flowchart(neighbourhood(backend, "core.services.standards", 3)))]),
        "notifications.md": page(
            "Notifications",
            "The notifications package (`core/services/notifications`), what uses it and what it uses.",
            [("Neighbourhood", flowchart(neighbourhood(backend, "core.services.notifications", 3)))]),
        "deployment.md": page(
            "Deployment",
            "Services in each Docker Compose file (with the files it includes; an arrow is `depends_on`), "
            "and the Nomad jobs: each group, how many run, its tasks and the services it registers.",
            [*[(str(p.relative_to(ROOT)), deployment(merged([p], yaml)))
               for p in sorted((ROOT / "local").glob("docker-compose*.y*ml"))],
             ("deployment/docker-compose.yml with docker-compose.prod.yml",
              deployment(merged([ROOT / "deployment/docker-compose.yml", ROOT / "deployment/docker-compose.prod.yml"], yaml))),
             ("Nomad jobs (deployment/*/*.nomad)", nomad(sorted((ROOT / "deployment").glob("*/*.nomad"))))]),
    }
    out["README.md"] = "\n".join([HEADER, "# Generated diagrams\n",
                                  "Drawn from the code by `docs/diagrams/generate.py`; a check fails when they differ.\n",
                                  *[f"- [{name[:-3]}]({name})" for name in sorted(out)], ""])
    return out


def main(argv: list[str]) -> int:
    wanted = pages()
    if "--check" in argv:
        stale = sorted(n for n, text in wanted.items() if not (OUT / n).exists() or (OUT / n).read_text() != text)
        stale += sorted(p.name for p in OUT.glob("*.md") if p.name not in wanted) if OUT.exists() else []
        if stale:
            print("out of date (run docs/diagrams/generate.py): " + ", ".join(stale))
            return 1
        print(f"{len(wanted)} generated diagrams up to date")
        return 0
    OUT.mkdir(exist_ok=True)
    for name, text in wanted.items():
        (OUT / name).write_text(text)
    print(f"wrote {len(wanted)} pages to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
